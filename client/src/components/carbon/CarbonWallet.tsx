export function CarbonWallet() {
  const [retireDialogOpen, setRetireDialogOpen] = useState(false);
  const [selectedInstrument, setSelectedInstrument] = useState<string>('ACCU');
  const [selectedMaxQty, setSelectedMaxQty] = useState(0);
  
  // Queries
  const { data: walletData, isLoading: walletLoading } = trpc.carbon.hasWallet.useQuery();
  const { data: balanceData, isLoading: balanceLoading, refetch: refetchBalance } = trpc.carbon.balance.useQuery(
    undefined,
    { enabled: walletData?.connected || walletData?.hasWallet }
  );
  const { data: pricesData } = trpc.carbon.prices.useQuery();
  const { data: impactData } = trpc.carbon.impactStats.useQuery(
    undefined,
    { enabled: walletData?.connected || walletData?.hasWallet }
  );
  
  // Mutations
  const retireMutation = trpc.carbon.retire.useMutation({
    onSuccess: (data) => {
      toast.success(
        <div>
          <p className="font-semibold">Units Retired Successfully!</p>
          <p className="text-sm">{data.quantity} {data.instrument} permanently retired.</p>
          <a 
            href={data.certificateUrl} 
            target="_blank" 
            rel="noopener noreferrer"
            className="text-sm text-blue-600 hover:underline flex items-center gap-1 mt-1"
          >
            View Certificate <ExternalLink className="h-3 w-3" />
          </a>
        </div>
      );
      setRetireDialogOpen(false);
      refetchBalance();
    },
    onError: (error) => {
      toast.error(`Retirement failed: ${error.message}`);
    },
  });
  
  const handleOpenRetire = (instrument: string, maxQty: number) => {
    setSelectedInstrument(instrument);
    setSelectedMaxQty(maxQty);
    setRetireDialogOpen(true);
  };
  
  const handleRetire = (data: { instrument: string; quantity: number; narrative: string }) => {
    retireMutation.mutate({
      instrument: data.instrument as 'ACCU' | 'SMC' | 'GO' | 'LGC',
      quantity: data.quantity,
      beneficiaryName: 'ABFI Grower', // Would come from user profile
      narrative: data.narrative,
    });
  };
  
  const isLoading = walletLoading || balanceLoading;
  
  // Normalize balance data to handle both old and new API structures
  const normalizedBalances = (() => {
    if (!balanceData) return null;
    
    // New structure: { balances: [...] }
    if (balanceData.balances && Array.isArray(balanceData.balances)) {
      return balanceData.balances;
    }
    
    // Old structure: { accu: {...}, smc: {...}, go: {...}, lgc: {...} }
    const oldData = balanceData as any;
    const instruments = ['accu', 'smc', 'go', 'lgc'];
    const balances: CarbonBalance[] = [];
    
    for (const inst of instruments) {
      if (oldData[inst]) {
        balances.push({
          instrument: inst.toUpperCase() as 'ACCU' | 'SMC' | 'GO' | 'LGC',
          available: oldData[inst].balance || 0,
          locked: 0,
          total: oldData[inst].balance || 0,
        });
      }
    }
    
    return balances.length > 0 ? balances : null;
  })();
  
  // Check if wallet is connected (handle both old and new API)
  const isWalletConnected = walletData?.connected ?? walletData?.hasWallet ?? false;
  
  // Price lookup helper
  const getPrice = (instrument: string) => {
    if (!pricesData) return undefined;
    
    // New structure: { prices: [...] }
    if (pricesData.prices && Array.isArray(pricesData.prices)) {
      return pricesData.prices.find(p => p.instrument === instrument);
    }
    
    // Old structure: array directly
    if (Array.isArray(pricesData)) {
      return (pricesData as any[]).find(p => p.instrument === instrument);
    }
    
    return undefined;
  };
  
  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex items-center justify-between">
        <div className="flex items-center gap-3">
          <div className="p-2 rounded-lg bg-green-100">
            <Wallet className="h-6 w-6 text-green-600" />
          </div>
          <div>
            <h2 className="text-xl font-bold">Carbon Wallet</h2>
            <p className="text-sm text-muted-foreground">
              Powered by Clean Energy Regulator (CorTenX)
            </p>
          </div>
        </div>
        
        {isWalletConnected && (
          <Badge variant="outline" className="gap-1 text-green-600 border-green-300">
            <CheckCircle2 className="h-3 w-3" />
            Connected
          </Badge>
        )}
      </div>
      
      {/* Impact Stats */}
      {impactData && impactData.totalRetired > 0 && (
        <ImpactTicker stats={impactData} />
      )}
      
      {/* Tabs */}
      <Tabs defaultValue="balances">
        <TabsList>
          <TabsTrigger value="balances">Balances</TabsTrigger>
          <TabsTrigger value="history">History</TabsTrigger>
        </TabsList>
        
        <TabsContent value="balances" className="mt-4">
          {isLoading ? (
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              {[1, 2, 3, 4].map((i) => (
                <div key={i} className="h-48 bg-muted animate-pulse rounded-lg" />
              ))}
            </div>
          ) : normalizedBalances && normalizedBalances.length > 0 ? (
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              {normalizedBalances.map((balance) => (
                <BalanceCard
                  key={balance.instrument}
                  balance={balance}
                  price={getPrice(balance.instrument)}
                  onRetire={handleOpenRetire}
                />
              ))}
            </div>
          ) : (
            <Card>
              <CardContent className="p-8 text-center">
                <Wallet className="h-12 w-12 mx-auto mb-4 text-muted-foreground opacity-50" />
                <h3 className="text-lg font-semibold mb-2">Connect Your Carbon Wallet</h3>
                <p className="text-muted-foreground mb-4">
                  Link your CER account to view and manage your carbon assets directly from ABFI.
                </p>
                <Button className="bg-green-600 hover:bg-green-700">
                  Verify Carbon Assets
                </Button>
              </CardContent>
            </Card>
          )}
          
          {/* Portfolio Summary */}
          {balanceData && (balanceData.portfolioValueAud || balanceData.totalValueAud) && (
            <Card className="mt-4">
              <CardContent className="p-4">
                <div className="flex items-center justify-between">
                  <div>
                    <p className="text-sm text-muted-foreground">Total Portfolio Value</p>
                    <p className="text-2xl font-bold">
                      ${(balanceData.portfolioValueAud ?? balanceData.totalValueAud ?? 0).toLocaleString(undefined, { 
                        minimumFractionDigits: 2, 
                        maximumFractionDigits: 2 
                      })}
                    </p>
                  </div>
                  {balanceData.lastUpdated && (
                    <div className="text-right">
                      <p className="text-xs text-muted-foreground">Last updated</p>
                      <p className="text-sm">
                        {new Date(balanceData.lastUpdated).toLocaleTimeString()}
                      </p>
                    </div>
                  )}
                </div>
              </CardContent>
            </Card>
          )}
        </TabsContent>
        
        <TabsContent value="history" className="mt-4">
          <TransactionHistory />
        </TabsContent>
      </Tabs>
      
      {/* Retire Dialog */}
      <RetireDialog
        open={retireDialogOpen}
        onOpenChange={setRetireDialogOpen}
        instrument={selectedInstrument}
        maxQty={selectedMaxQty}
        onRetire={handleRetire}
        isLoading={retireMutation.isPending}
      />
    </div>
  );
}

export default CarbonWallet;
