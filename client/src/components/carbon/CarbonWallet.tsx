function BalanceCard({ 
  balance, 
  price,
  onRetire,
}: { 
  balance: CarbonBalance; 
  price?: CarbonPrice;
  onRetire: (instrument: string, maxQty: number) => void;
}) {
  const info = INSTRUMENT_INFO[balance.instrument];
  const Icon = info.icon;
  const valueAud = price ? balance.available * price.spotPrice : null;
  
  return (
    <Card className={cn("relative overflow-hidden", balance.available > 0 && "border-l-4 border-l-green-500")}>
      <CardContent className="p-4">
        <div className="flex items-start justify-between">
          <div className="flex items-center gap-3">
            <div className={cn("p-2 rounded-lg", info.bgColor)}>
              <Icon className={cn("h-5 w-5", info.color)} />
            </div>
            <div>
              <p className="font-semibold">{balance.instrument}</p>
              <Tooltip>
                <TooltipTrigger asChild>
                  <p className="text-xs text-muted-foreground cursor-help">{info.name}</p>
                </TooltipTrigger>
                <TooltipContent className="max-w-xs">
                  <p>{info.description}</p>
                </TooltipContent>
              </Tooltip>
            </div>
          </div>
          
          {price && (
            <div className="text-right">
              <p className="text-sm font-medium">${(price.spotPrice ?? price.priceAud ?? 0).toFixed(2)}</p>
              <p className={cn(
                "text-xs flex items-center gap-1",
                (price.change24h ?? 0) >= 0 ? "text-green-600" : "text-red-600"
              )}>
                {(price.change24h ?? 0) >= 0 ? <TrendingUp className="h-3 w-3" /> : <TrendingDown className="h-3 w-3" />}
                {(price.change24h ?? 0) >= 0 ? '+' : ''}{(price.change24h ?? 0).toFixed(2)}%
              </p>
            </div>
          )}
        </div>
        
        <div className="mt-4 grid grid-cols-3 gap-2 text-center">
          <div>
            <p className="text-2xl font-bold">{(balance.available ?? 0).toLocaleString()}</p>
            <p className="text-xs text-muted-foreground">Available</p>
          </div>
          <div>
            <p className="text-lg text-muted-foreground">{(balance.locked ?? 0).toLocaleString()}</p>
            <p className="text-xs text-muted-foreground">Locked</p>
          </div>
          <div>
            <p className="text-lg text-muted-foreground">{(balance.total ?? 0).toLocaleString()}</p>
            <p className="text-xs text-muted-foreground">Total</p>
          </div>
        </div>
        
        {valueAud && valueAud > 0 && (
          <div className="mt-3 pt-3 border-t">
            <p className="text-sm text-muted-foreground">
              Portfolio value: <span className="font-semibold text-foreground">${(valueAud ?? 0).toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}</span>
            </p>
          </div>
        )}
        
        {(balance.available ?? 0) > 0 && (
          <Button 
            variant="outline" 
            size="sm" 
            className="w-full mt-3"
            onClick={() => onRetire(balance.instrument, balance.available)}
          >
            Retire Units
            <ArrowRight className="h-4 w-4 ml-2" />
          </Button>
        )}
      </CardContent>
    </Card>
  );
}

