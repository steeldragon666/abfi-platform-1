// ============================================================================
// TYPES
// ============================================================================

interface CarbonBalance {
  instrument: 'ACCU' | 'SMC' | 'GO' | 'LGC';
  available: number;
  locked: number;
  total: number;
}

interface CarbonPrice {
  instrument: string;
  spotPrice: number;
  change24h: number;
}

// ============================================================================
// CONSTANTS
// ============================================================================

const INSTRUMENT_INFO = {
  ACCU: {
    name: 'Australian Carbon Credit Unit',
    description: 'Each ACCU represents 1 tonne of CO₂ equivalent emissions avoided or removed.',
    color: 'text-green-600',
    bgColor: 'bg-green-100',
    icon: Leaf,
  },
  SMC: {
    name: 'Safeguard Mechanism Credit',
    description: 'Credits generated by facilities that reduce emissions below their baseline.',
    color: 'text-blue-600',
    bgColor: 'bg-blue-100',
    icon: Shield,
  },
  GO: {
    name: 'Guarantee of Origin',
    description: 'Certificates that verify electricity came from renewable sources.',
    color: 'text-amber-600',
    bgColor: 'bg-amber-100',
    icon: Zap,
  },
  LGC: {
    name: 'Large-scale Generation Certificate',
    description: 'Certificates from large-scale renewable energy generation.',
    color: 'text-purple-600',
    bgColor: 'bg-purple-100',
    icon: Award,
  },
};

