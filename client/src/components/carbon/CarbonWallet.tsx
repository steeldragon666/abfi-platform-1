function RetireDialog({ 
  open, 
  onOpenChange, 
  instrument, 
  maxQty,
  onRetire,
  isLoading,
}: { 
  open: boolean;
  onOpenChange: (open: boolean) => void;
  instrument: string;
  maxQty: number;
  onRetire: (data: { instrument: string; quantity: number; narrative: string }) => void;
  isLoading: boolean;
}) {
  const [quantity, setQuantity] = useState(Math.min(100, maxQty));
  const [narrative, setNarrative] = useState('');
  
  const handleRetire = () => {
    if (quantity <= 0 || quantity > maxQty) {
      toast.error('Invalid quantity');
      return;
    }
    if (narrative.length < 10) {
      toast.error('Please provide a retirement narrative (min 10 characters)');
      return;
    }
    onRetire({ instrument, quantity, narrative });
  };
  
  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="sm:max-w-md">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2">
            <Leaf className="h-5 w-5 text-green-600" />
            Retire {instrument} Units
          </DialogTitle>
          <DialogDescription>
            Permanently retire carbon units. This action cannot be undone.
          </DialogDescription>
        </DialogHeader>
        
        <div className="space-y-4 py-4">
          <div className="space-y-2">
            <div className="flex justify-between">
              <Label>Quantity to Retire</Label>
              <span className="text-sm text-muted-foreground">Max: {(maxQty ?? 0).toLocaleString()}</span>
            </div>
            <div className="flex items-center gap-4">
              <Slider
                value={[quantity]}
                min={1}
                max={maxQty}
                step={1}
                onValueChange={(v) => setQuantity(v[0])}
                className="flex-1"
              />
              <Input
                type="number"
                value={quantity}
                onChange={(e) => setQuantity(Math.min(maxQty, Math.max(1, parseInt(e.target.value) || 1)))}
                className="w-24"
              />
            </div>
          </div>
          
          <div className="space-y-2">
            <Label>Retirement Narrative</Label>
            <Textarea
              placeholder="e.g., Retired on behalf of [Company Name] for [Project/Delivery Reference]"
              value={narrative}
              onChange={(e) => setNarrative(e.target.value)}
              rows={3}
            />
            <p className="text-xs text-muted-foreground">
              This narrative will appear on the public retirement certificate.
            </p>
          </div>
          
          <div className="p-3 rounded-lg bg-amber-50 border border-amber-200">
            <div className="flex items-start gap-2">
              <AlertCircle className="h-4 w-4 text-amber-600 mt-0.5" />
              <div>
                <p className="text-sm font-medium text-amber-800">Permanent Action</p>
                <p className="text-xs text-amber-600">
                  Retired units are permanently removed from circulation and cannot be recovered.
                </p>
              </div>
            </div>
          </div>
        </div>
        
        <DialogFooter>
          <Button variant="outline" onClick={() => onOpenChange(false)}>
            Cancel
          </Button>
          <Button 
            onClick={handleRetire}
            disabled={isLoading || quantity <= 0 || narrative.length < 10}
            className="bg-green-600 hover:bg-green-700"
          >
            {isLoading ? (
              <>
                <RefreshCw className="h-4 w-4 mr-2 animate-spin" />
                Processing...
              </>
            ) : (
              <>
                <CheckCircle2 className="h-4 w-4 mr-2" />
                Retire {(quantity ?? 0).toLocaleString()} Units
              </>
            )}
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}

function TransactionHistory({ userId }: { userId?: number }) {
  const { data: historyData, isLoading } = trpc.carbon.history.useQuery({ limit: 10 });
  
  if (isLoading) {
    return (
      <div className="space-y-2">
        {[1, 2, 3].map((i) => (
          <div key={i} className="h-16 bg-muted animate-pulse rounded-lg" />
        ))}
      </div>
    );
  }
  
  const transactions = historyData?.transactions || [];
  
  if (transactions.length === 0) {
    return (
      <div className="text-center py-8 text-muted-foreground">
        <Clock className="h-8 w-8 mx-auto mb-2 opacity-50" />
        <p>No transactions yet</p>
      </div>
    );
  }
  
  return (
    <div className="space-y-2">
      {transactions.map((txn) => (
        <div 
          key={txn.id}
          className="flex items-center justify-between p-3 rounded-lg border bg-card hover:bg-muted/50 transition-colors"
        >
          <div className="flex items-center gap-3">
            <div className={cn(
              "p-2 rounded-full",
              txn.txnType === 'IN' && "bg-green-100",
              txn.txnType === 'OUT' && "bg-red-100",
              txn.txnType === 'RETIRE' && "bg-blue-100",
              txn.txnType === 'BUNDLE_LOCK' && "bg-purple-100",
            )}>
              {txn.txnType === 'IN' && <TrendingUp className="h-4 w-4 text-green-600" />}
              {txn.txnType === 'OUT' && <TrendingDown className="h-4 w-4 text-red-600" />}
              {txn.txnType === 'RETIRE' && <CheckCircle2 className="h-4 w-4 text-blue-600" />}
              {txn.txnType === 'BUNDLE_LOCK' && <Shield className="h-4 w-4 text-purple-600" />}
            </div>
            <div>
              <p className="font-medium">
                {txn.txnType === 'IN' && 'Received'}
                {txn.txnType === 'OUT' && 'Transferred'}
                {txn.txnType === 'RETIRE' && 'Retired'}
                {txn.txnType === 'BUNDLE_LOCK' && 'Locked in Bundle'}
                {' '}{(txn.quantity ?? 0).toLocaleString()} {txn.instrument}
              </p>
              <p className="text-xs text-muted-foreground">
                {new Date(txn.createdAt).toLocaleDateString()}
              </p>
            </div>
          </div>
          
          {txn.registryUrl && (
            <Button variant="ghost" size="sm" asChild>
              <a href={txn.registryUrl} target="_blank" rel="noopener noreferrer">
                <ExternalLink className="h-4 w-4" />
              </a>
            </Button>
          )}
        </div>
      ))}
    </div>
  );
}

